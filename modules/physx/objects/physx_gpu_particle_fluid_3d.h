#pragma once

#include "core/math/aabb.h"
#include "core/math/vector3.h"
#include "core/math/vector4.h"
#include "core/os/mutex.h"
#include "core/templates/local_vector.h"
#include "core/templates/rid.h"
#include "core/templates/vector.h"

namespace physx {
class PxPBDParticleSystem;
class PxPBDMaterial;
class PxParticleAndDiffuseBuffer;
} //namespace physx

class PhysXSpace3D;
struct PhysXFluidIsosurface;

// A GPU PBD fluid (PhysX 5 PxPBDParticleSystem). GPU-only; on a CPU build or
// without a CUDA device it stays inert. Owned in a space; positions are read
// back from the GPU after each step for the node to render.
class PhysXGPUParticleFluid3D {
	friend struct PhysXFluidIsosurface;

public:
	enum Param {
		PARAM_VISCOSITY,
		PARAM_SURFACE_TENSION,
		PARAM_COHESION,
		PARAM_SURFACE_FRICTION,
		PARAM_ADHESION,
		PARAM_VORTICITY,
		PARAM_GRAVITY_SCALE,
		PARAM_PARTICLE_SIZE,
		PARAM_MAX,
	};

private:
	RID self;
	PhysXSpace3D *space = nullptr;

	physx::PxPBDParticleSystem *px_system = nullptr;
	physx::PxPBDMaterial *px_material = nullptr;
	physx::PxParticleAndDiffuseBuffer *px_buffer = nullptr;
	uint32_t fluid_phase = 0;

	uint32_t capacity = 8192; // particle buffer size
	uint32_t active_count = 0;
	uint32_t write_head = 0; // next slot to (over)write; ring-buffers when full

	// Diffuse (foam/spray/bubble) particles generated by the solver.
	bool foam_enabled = false;
	uint32_t foam_capacity = 16384;
	real_t foam_lifetime = 1.5;
	real_t foam_threshold = 300.0; // solver potential above which foam spawns
	real_t foam_buoyancy = 0.9;
	real_t foam_size = 0.1; // froth clump scale for the foam isosurface, independent of particle_size
	bool dirty_foam = true;
	uint32_t foam_count = 0;
	LocalVector<Vector4> foam_scratch; // pos.xyz + remaining lifetime.w
	LocalVector<Vector3> foam_positions;

	real_t viscosity = 0.01;
	real_t surface_tension = 0.006;
	real_t cohesion = 0.02;
	real_t adhesion = 0.0;
	real_t surface_friction = 0.2;
	real_t vorticity = 8.0;
	real_t gravity_scale = 1.0;
	real_t particle_size = 0.1; // spacing between particles at rest, in meters

	// Granular phase: solid grains (no fluid density constraint) that pile and
	// hold a slope. Changing it recreates the particle system.
	bool granular = false;
	real_t granular_friction = 0.7; // PBD friction coefficient (~ tan of the repose angle)

	bool dirty_material = true;

	LocalVector<Vector4> read_scratch; // pos.xyz + inv-mass.w, one per active particle
	LocalVector<Vector3> read_positions;

	// GPU isosurface: PhysX marching-cubes a smooth triangle mesh from the
	// particles (PxIsosurfaceExtractor + smoothing + anisotropy). The mesh is
	// read back to these arrays each step for the node to draw as an ArrayMesh.
	bool surface_mesh_enabled = false;
	// Feed PhysX per-particle anisotropy to the extractor: sharper crests and
	// thinner sheets, but it needles fast/isolated particles, so it is opt-in and
	// meant for settled pools rather than actively-emitting fluid.
	bool surface_anisotropy_enabled = false;
	PhysXFluidIsosurface *iso = nullptr;
	mutable Mutex mesh_mutex;
	LocalVector<Vector3> mesh_vertices;
	LocalVector<Vector3> mesh_normals;
	LocalVector<int32_t> mesh_indices;
	uint32_t mesh_version = 0; // bumped each time the isosurface is re-extracted

	// Second, coarser isosurface over the diffuse (foam) particles -- a frothy
	// layer drawn on top of the fluid surface. Only produced when both
	// surface_mesh_enabled and foam_enabled are set.
	mutable Mutex foam_mesh_mutex;
	LocalVector<Vector3> foam_mesh_vertices;
	LocalVector<Vector3> foam_mesh_normals;
	LocalVector<int32_t> foam_mesh_indices;
	uint32_t foam_mesh_version = 0;

	void _ensure_isosurface();
	void _destroy_isosurface();

	void _destroy();
	void _ensure_system();
	void _ensure_buffer();
	void _apply_material();
	void _apply_foam_params();
	void _write_particles(uint32_t p_at, const Vector<Vector3> &p_positions, const Vector3 &p_velocity);

public:
	void set_self(const RID &p_self) { self = p_self; }
	RID get_self() const { return self; }

	void set_space(PhysXSpace3D *p_space);
	PhysXSpace3D *get_space() const { return space; }

	void set_param(Param p_param, real_t p_value);
	real_t get_param(Param p_param) const;
	void set_capacity(uint32_t p_capacity);
	uint32_t get_capacity() const { return capacity; }

	// Granular grains instead of a fluid. Toggling rebuilds the particle system.
	void set_granular(bool p_enabled, real_t p_friction);
	bool is_granular() const { return granular; }

	// Diffuse particles. Enabling/resizing rebuilds the buffer; the rest push live.
	void set_foam_enabled(bool p_enabled);
	bool is_foam_enabled() const { return foam_enabled; }
	void set_foam_capacity(uint32_t p_capacity);
	uint32_t get_foam_capacity() const { return foam_capacity; }
	void set_foam_lifetime(real_t p_v);
	void set_foam_threshold(real_t p_v);
	void set_foam_buoyancy(real_t p_v);
	void set_foam_size(real_t p_v);
	real_t get_foam_lifetime() const { return foam_lifetime; }
	real_t get_foam_threshold() const { return foam_threshold; }
	real_t get_foam_buoyancy() const { return foam_buoyancy; }
	real_t get_foam_size() const { return foam_size; }
	const LocalVector<Vector3> &get_foam_positions() const { return foam_positions; }
	uint32_t get_foam_count() const { return foam_count; }

	// Replace the live particle set with a block at the given positions.
	void set_particles(const Vector<Vector3> &p_positions, const Vector3 &p_initial_velocity);
	// Add particles to the live set, recycling the oldest once the buffer is full.
	void emit(const Vector<Vector3> &p_positions, const Vector3 &p_velocity);
	void clear();

	// Called by the space after fetchResults(): copy positions GPU -> host.
	void read_back();
	const LocalVector<Vector3> &get_positions() const { return read_positions; }
	uint32_t get_particle_count() const { return active_count; }

	// Batched multi-fluid isosurface readback. With more than one fluid in a
	// space, the space defers each fluid's outlier-clamp sync out of
	// onPostSolve (where N fluids would serialize N GPU stalls mid-solve) and
	// calls finish_isosurface_extraction() once per fluid after fetchResults,
	// when every fluid's smoothing kernel is already in flight. Single-fluid
	// spaces keep the inline path (flag false).
	void set_deferred_extraction(bool p_deferred);
	void finish_isosurface_extraction();

	// GPU isosurface mesh (PxIsosurfaceExtractor). Enabling creates the extractor.
	void set_surface_mesh_enabled(bool p_enabled);
	bool is_surface_mesh_enabled() const { return surface_mesh_enabled; }
	void set_surface_anisotropy_enabled(bool p_enabled) { surface_anisotropy_enabled = p_enabled; }
	bool is_surface_anisotropy_enabled() const { return surface_anisotropy_enabled; }
	// Triangle count of the latest isosurface (0 until the first extraction
	// publishes). Cheap script-facing probe that copies nothing.
	uint32_t get_surface_triangle_count() const;
	// Thread-safe copy of the latest isosurface. Returns the triangle count.
	// p_have_version is the caller's last-seen mesh_version; if it still matches,
	// nothing is copied and r_* are left untouched (caller should skip its rebuild).
	uint32_t copy_surface_mesh(LocalVector<Vector3> &r_vertices, LocalVector<Vector3> &r_normals, LocalVector<int32_t> &r_indices, uint32_t &p_have_version) const;
	// Same, for the foam isosurface layer.
	uint32_t copy_foam_mesh(LocalVector<Vector3> &r_vertices, LocalVector<Vector3> &r_normals, LocalVector<int32_t> &r_indices, uint32_t &p_have_version) const;

	// Fraction (0..1) of the world-space box filled by fluid, from the fraction
	// of particles inside it scaled by particle volume. A cheap buoyancy probe.
	real_t get_submersion(const AABB &p_world_aabb) const;

	bool is_ready() const { return px_system != nullptr; }

	/// True when this platform's SDK libraries provide the CUDA particle+diffuse
	/// buffer factory (ExtGpu::PxCreateAndPopulateParticleAndDiffuseBuffer). It
	/// ships only in the GPU-enabled Windows libraries; elsewhere the module
	/// stubs it (see physx_extgpu_stub_linux.cpp) and no PBD fluid buffer can
	/// be created, foam or not. The MPM (Vulkan compute) backend is the
	/// cross-platform path.
	static bool supports_diffuse_particles();

	PhysXGPUParticleFluid3D() {}
	~PhysXGPUParticleFluid3D();
};
